    /** Accepts the usual spellings; {@code Boolean.getBoolean} only understands "true". */
    private static boolean truthy(String value) {
        return value != null && ("1".equals(value) || "true".equalsIgnoreCase(value)
                || "yes".equalsIgnoreCase(value) || "on".equalsIgnoreCase(value));
    }

    /**
     * Whether the agent should short-circuit {@code getHealth()} for this entity.
     *
     * <p>Only players that the mod itself considers protected, and for which a bypass
     * health record exists, qualify. Player-less entities are never touched.
     *
     * <p>Timed through {@link ReconcileStats#GET_HEALTH}; this is one of the hottest
     * entry points in the whole design.
     */
    public static boolean shouldOverrideGetHealth(Object self) {
        HOOK_CALLS.incrementAndGet();
        HookLiveness.mark("getHealth");
        long stat = ReconcileStats.GET_HEALTH.start();
        boolean override = computeShouldOverrideGetHealth(self);
        ReconcileStats.GET_HEALTH.end(stat, override);
        return override;
    }

    /**
     * Monotonic counter of {@code getHealth} hook invocations.
     *
     * <p>The agent's watchdog polls this reflectively: JVMTI always hands a retransform the
     * <em>initial</em> define-time bytes, so byte comparison cannot tell whether somebody
     * redefined the class after us. A stalled counter can: our injected call is demonstrably
     * no longer running, which means the method body was replaced by someone else.
     */
    public static long hookCallCount() {
        return HOOK_CALLS.get();
    }

    private static boolean computeShouldOverrideGetHealth(Object self) {
        if (PlayerDefense.isRawReadProbe()) {
            // 原始读值探测中：不短接方法体，让调用方看到外部实现替换后的真实返回值。
            return false;
        }
        if (!(self instanceof Player player)) {
            return false;
        }
        if (FORCE_PROTECTED) {
            ModLog.healthThrottled("AgentHooks.forced:" + player.getUUID(), ModLog.TICK_INTERVAL,
                    "AgentHooks[层=agent getHealth BODY] 强制保护开关生效，返回值由桥接层给出", player,
                    "返回=" + FORCED_HEALTH);
            return true;
        }
        try {
            // 不以 isProtected 为前提：外部实现整体替换 getHealth() 时根本不看保护状态机，
            // 这里也不能把保护状态当门槛，只看“我们是否持有该玩家的权威血量（> 0）”。
            return PlayerDefense.hasAuthoritativeHealth(player);
        } catch (Throwable t) {
            // Any failure means "no opinion": fall back to the normal (Mixin-instrumented) body.
            return false;
        }
    }

    /** The value {@code getHealth()} should return when {@link #shouldOverrideGetHealth} said yes. */
    public static float overriddenGetHealth(Object self) {
        if (!(self instanceof Player player)) {
            return 0.0F;
        }
        if (FORCE_PROTECTED) {
            return FORCED_HEALTH;
        }
        try {
            float real = PlayerDefense.getRealHealth(player, Float.NaN);
            if (!Float.isNaN(real)) {
                // 全模组最热的读取点（每个实体每次 getHealth）：发布版连 describe() 都不做。
                if (ModLog.ENABLED) {
                    ModLog.healthThrottled("AgentHooks.hit:" + player.getUUID(), ModLog.TICK_INTERVAL,
                            "AgentHooks[层=agent getHealth BODY] 用旁路真实血量作为返回值", player,
                            "返回=" + real);
                }
                return real;
            }
            // Client side before the first sync packet arrives: never expose a dropped value.
            if (player.level().isClientSide) {
                float max = player.getMaxHealth();
                if (!Float.isNaN(max) && !Float.isInfinite(max) && max > 0.0F) {
                    return max;
                }
            }
        } catch (Throwable ignored) {
            // fall through
        }
        return 0.0F;
    }

