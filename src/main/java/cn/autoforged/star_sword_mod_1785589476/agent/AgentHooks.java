    /** {@code OBSERVE} 规则的命中计数（规则 id -> 次数）；没有观察规则时为空。 */
    private static final java.util.Map<String, java.util.concurrent.atomic.LongAdder> OBSERVED_HITS =
            new java.util.concurrent.ConcurrentHashMap<>();

    /**
     * {@code OBSERVE} 规则的计数入口：只记数，不影响原逻辑。
     *
     * <p>灰度观察用的规则由 {@code Rules.Kind.OBSERVE} 生成，注入片段形如
     * {@code { AgentHooks.noteObserved("rule.id", $0); }}——它是 HEAD 插入，原方法照常执行。
     * 这样"某条规则会被调用多少次"可以先量出来，再决定要不要把它升级成 REPLACE。
     */
    public static void noteObserved(String ruleId, Object self) {
        if (ruleId == null) {
            return;
        }
        OBSERVED_HITS.computeIfAbsent(ruleId,
                key -> new java.util.concurrent.atomic.LongAdder()).increment();
    }

    /** 观察规则的命中摘要；没有观察规则时返回空串。 */
    public static String describeObserved() {
        if (OBSERVED_HITS.isEmpty()) {
            return "";
        }
        StringBuilder sb = new StringBuilder();
        for (java.util.Map.Entry<String, java.util.concurrent.atomic.LongAdder> entry
                : OBSERVED_HITS.entrySet()) {
            if (sb.length() > 0) {
                sb.append(", ");
            }
            sb.append(entry.getKey()).append('=').append(entry.getValue().sum());
        }
        return sb.toString();
    }

    /** agent 上报的“当前真有我们的注入在跑”的键集合；每轮重放后整体替换。 */
    private static volatile java.util.Set<String> agentInjections = java.util.Set.of();

    /** 注入对账：声明总条数与「被单类降级剔除」「目标方法不存在」的键。 */
    private static volatile int declaredInjections = -1;
    private static volatile java.util.Set<String> suppressedInjections = java.util.Set.of();
    private static volatile java.util.Set<String> notApplicableInjections = java.util.Set.of();
    private static volatile boolean injectionBannerLogged;

    /**
     * agent 每轮把注入状态整体同步过来。
     *
     * <p>覆盖语义而不是累加：注入被单类降级剔除、或 watchdog 重新注册 transformer 之后，
     * 旧结论必须失效，否则 Mixin 兜底会因为“agent 已接管”而永久让路，形成静默空洞。
     *
     * <p>三个数字对应三种事实：<b>声明</b>（注入表里写了多少条）、<b>已应用</b>（真的装上了）、
     * <b>已剔除</b>（装不上的那些）。没有这三个数字，"覆盖矩阵"就只是手写声明。
     */
    public static void reportInjectionState(String[] applied, String[] suppressed, String[] notApplicable,
                                            int declared) {
        java.util.Set<String> nextApplied = toKeySet(applied);
        // 整体替换而不是先 clear 再 add：正在处理 setHealth 的线程不会看到“空窗口”而多过滤一次。
        agentInjections = nextApplied;
        suppressedInjections = toKeySet(suppressed);
        notApplicableInjections = toKeySet(notApplicable);
        declaredInjections = declared;
        if (!injectionBannerLogged) {
            injectionBannerLogged = true;
            ModLog.log(ModLog.AGENT, "注入对账: " + describeInjectionState());
        }
    }

    private static java.util.Set<String> toKeySet(String[] keys) {
        java.util.Set<String> next = java.util.concurrent.ConcurrentHashMap.newKeySet();
        if (keys != null) {
            for (String key : keys) {
                if (key != null && !key.isBlank()) {
                    next.add(key);
                }
            }
        }
        return next;
    }

    /** 某个入口当前是否真的由 agent 接管（Mixin 据此决定是否让路）。 */
    public static boolean hasAgentInjection(String key) {
        return agentInjections.contains(key);
    }

    /** 一行对账摘要：声明 / 已应用 / 方法不存在 / 已剔除。 */
    public static String describeInjectionState() {
        if (declaredInjections < 0) {
            return "等待 agent 上报";
        }
        StringBuilder sb = new StringBuilder()
                .append("声明 ").append(declaredInjections).append(" 条 / 已应用 ")
                .append(agentInjections.size()).append(" 条 / 方法不存在 ")
                .append(notApplicableInjections.size()).append(" 条 / 已剔除 ")
                .append(suppressedInjections.size()).append(" 条");
        if (!notApplicableInjections.isEmpty()) {
            sb.append("；不存在: ").append(joinShort(notApplicableInjections, 4));
        }
        if (!suppressedInjections.isEmpty()) {
            sb.append("；剔除: ").append(joinShort(suppressedInjections, 4));
        }
        return sb.toString();
    }

    /** 最多列 {@code limit} 条，超出用省略号。 */
    private static String joinShort(java.util.Set<String> keys, int limit) {
        StringBuilder sb = new StringBuilder();
        int shown = 0;
        for (String key : keys) {
            if (shown > 0) {
                sb.append(", ");
            }
            if (++shown > limit) {
                sb.append("…");
                break;
            }
            sb.append(shortKey(key));
        }
        return sb.toString();
    }

    /** 注入键的人读形式：{@code 类名#方法名} 去掉包名；规则 id 原样返回。 */
    private static String shortKey(String key) {
        int hash = key.indexOf('#');
        if (hash < 0) {
            return key;
        }
        String type = key.substring(0, hash);
        int dot = type.lastIndexOf('.');
        return (dot < 0 ? type : type.substring(dot + 1)) + key.substring(hash);
    }

    /**
     * {@code LivingEntity.setHealth(float)} 的入参归一 + 受保护玩家写入过滤。
     *
     * <p>原实现是 Mixin 的 {@code @ModifyVariable}；现在由 agent 在方法 HEAD 就地把 {@code $1}
     * 改写成这里的返回值，Mixin 只在 agent 没有接管该入口时调用同一个方法——判据只有一份，
     * 同一次写入也只过滤一次（重复调用会让 {@code countWrite} 翻倍）。
     *
     * <p>职责分离：NaN / 无限对所有 {@code LivingEntity} 生效；“减血拒绝”只对受保护玩家生效
     * （见 {@link PlayerDefense#filterHealthWrite}）。负数不在此处理——致命伤害产生的负数是
     * 正常中间值，由原版 {@code setHealth} 内部 clamp。
     */
    public static float filterSetHealthArg(Object self, float value) {
        if (!(self instanceof LivingEntity entity)) {
            return value;
        }
        float sanitized = value;
        if (Float.isNaN(sanitized) || Float.isInfinite(sanitized)) {
            ModLog.health("sanitizeHealth 非法血量入参，替换为合法值", entity, "原值=" + sanitized);
            float replacement = entity.getMaxHealth();
            if (Float.isNaN(replacement) || Float.isInfinite(replacement) || replacement < 0.0F) {
                replacement = entity.getHealth();
                if (Float.isNaN(replacement) || Float.isInfinite(replacement) || replacement < 0.0F) {
                    replacement = 0.0F;
                }
            }
            sanitized = replacement;
        }
        return PlayerDefense.filterHealthWrite(entity, sanitized);
    }

