    /**
     * {@code LivingEntity.hurt(DamageSource, float)}: cancel damage against a protected
     * player. The counter-attack side effect is shared with the Mixin handler through
     * {@link CounterAttack}, because an early return here would otherwise skip it.
     */
    public static boolean shouldCancelHurt(Object self, Object source, float amount) {
        HookLiveness.mark("hurt");
        if (!(self instanceof Player player)) {
            return false;
        }
        try {
            if (!FORCE_PROTECTED && !SwordGuard.isProtected(player)) {
                return false;
            }
            if (source instanceof DamageSource damageSource) {
                CounterAttack.onHurt(player, damageSource, amount);
            }
            return hit(player, "hurt");
        } catch (Throwable t) {
            return false;
        }
    }

    /** Throttled "this gate fired" line, so every gate is observable in a dev run. */
    private static boolean hit(Player player, String gate) {
        if (ModLog.ENABLED) {
            ModLog.defenseThrottled("AgentHooks." + gate + ":" + player.getUUID(), ModLog.TICK_INTERVAL,
                    "AgentHooks[层=agent " + gate + "] 命中，方法已被改写", player,
                    "force=" + FORCE_PROTECTED);
        }
        return true;
    }

    /**
     * 整段替换后的 {@code getHealth()} 实现。
     *
     * <p>agent 把方法体换成 {@code return AgentHooks.getHealthBody($0);}，原实现另存为
     * {@code starSword$originalGetHealth}。因此返回值完全由这里决定，<b>不再依赖任何注入点位置</b>
     * ——包括 RETURN 侧（javassist 的 insertAfter 在本方法上会产出不可验证的字节码，已弃用）。
     *
     * <p>三条路径：
     * <ol>
     *   <li>读取侧自检期间（探测中）：调用原实现，取「未经我们处理」的真实读数；</li>
     *   <li>我们对该玩家有意见：返回权威血量；</li>
     *   <li>其余：调用原实现，保持原版语义。</li>
     * </ol>
     */
    public static float getHealthBody(Object self) {
        try {
            if (!(self instanceof LivingEntity entity)) {
                return 0.0F;
            }
            if (!PlayerDefense.isRawReadProbe() && shouldOverrideGetHealth(self)) {
                return overriddenGetHealth(self);
            }
            // 没有意见（或正在做取值探测）：按原版语义直接读血量同步项。
            // 走字段直读，不经过 getHealth 自身，因此不递归；也不依赖方法体里还有什么。
            // 但读出来的值仍可能被外部写成算式结果（负数 / NaN），必须过读取裁决，
            // 否则这里会把负血原样交给调用方，让 `<= 0` 判死。
            float raw = PlayerDefense.rawSyncedHealth(entity);
            if (Float.isNaN(raw)) {
                return 0.0F;
            }
            return cn.autoforged.star_sword_mod_1785589476.hijack.authority.HealthAuthority
                    .renderRead(entity, raw);
        } catch (Throwable throwable) {
            return 0.0F;
        }
    }

    /**
     * {@code Entity.isAlive()} 的整段替换实现。
     *
     * <p>原版语义是"没被移除即活着"。它与死亡判定同源，且被 AI、渲染、交互大量读取，
     * 因此也交给 {@link HealthJudgement}：防御态一律"活着"，其余保持原版语义。
     */
    public static boolean isAlive(Object self) {
        HookLiveness.mark("isAlive");
        try {
            if (!(self instanceof Entity entity)) {
                return false;
            }
            if (entity instanceof LivingEntity living && HealthJudgement.isDeathBlocked(living)) {
                return true;
            }
            return !entity.isRemoved();
        } catch (Throwable throwable) {
            return true;
        }
    }

    /**
     * Phase 3：{@code isDeadOrDying()} 的<b>整段替换</b>实现。
     *
     * <p>agent 把方法体换成 {@code return AgentHooks.isDeadOrDying($0);}，因此原版那句
     * {@code getHealth() <= 0} 不再出现在方法里——外部实现替换 {@code getHealth()} 也不会让这条链复活。
     * 判据交给 {@link HealthJudgement}：防御态一律「没死」，其余按权威血量判。
     *
     * @param self 被调用的实体（注入点的 {@code $0}）
     */
    public static boolean isDeadOrDying(Object self) {
        HookLiveness.mark("isDeadOrDying");
        try {
            if (!(self instanceof LivingEntity entity)) {
                return false;
            }
            if (FORCE_PROTECTED && entity instanceof Player player) {
                hit(player, "isDeadOrDying(body)");
                return false;
            }
            return HealthJudgement.isDead(entity);
        } catch (Throwable throwable) {
            // 判定器绝不抛；真出了意外也只回答「没死」，不把实体判死。
            return false;
        }
    }

    /** {@code LivingEntity.isDeadOrDying()} and {@code tickDeath()}: protected players never die. */
    public static boolean shouldSuppressDeath(Object self) {
        if (!(self instanceof Player player)) {
            return false;
        }
        if (FORCE_PROTECTED) {
            return hit(player, "isDeadOrDying/tickDeath");
        }
        try {
            return SwordGuard.isProtected(player) && hit(player, "isDeadOrDying/tickDeath");
        } catch (Throwable t) {
            return false;
        }
    }

    /** {@code die(DamageSource)} — declared by LivingEntity, Player and ServerPlayer. */
    public static boolean shouldBlockDie(Object self) {
        if (!(self instanceof Player player)) {
            return false;
        }
        if (FORCE_PROTECTED) {
            return hit(player, "die");
        }
        try {
            return SwordGuard.shouldBlockDirectDie(player) && hit(player, "die");
        } catch (Throwable t) {
            return false;
        }
    }

    /** {@code dropAllDeathLoot(DamageSource)}: never let a protected player's inventory spill. */
